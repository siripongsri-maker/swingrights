/** Normalise a province name to a lookup key ("จังหวัดเชียงใหม่" → "เชียงใหม่", "กรุงเทพมหานคร" → "กรุงเทพ"). */
export const normProvince = (s?: string | null): string =>
  (s ?? '')
    .replace(/^(จังหวัด|จ\.)\s*/, '')
    .replace(/^กรุงเทพ.*$/, 'กรุงเทพ')
    .trim();

export const provinceCoords = (province?: string | null): [number, number] | null =>
  PROVINCE_GEO[normProvince(province)] ?? null;

/** Straight-line distance in km between two provinces, or null if either is unknown. */
export function provinceDistanceKm(a?: string | null, b?: string | null): number | null {
  const ca = provinceCoords(a);
  const cb = provinceCoords(b);
  if (!ca || !cb) return null;
  const toRad = (d: number) => (d * Math.PI) / 180;
  const R = 6371;
  const dLat = toRad(cb[0] - ca[0]);
  const dLng = toRad(cb[1] - ca[1]);
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(ca[0])) * Math.cos(toRad(cb[0])) * Math.sin(dLng / 2) ** 2;
  return Math.round(2 * R * Math.asin(Math.sqrt(h)));
}
